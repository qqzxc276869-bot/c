// 数据类型的重命名
typedef unsigned char u8;       // 0~255
typedef unsigned int  u16;      // 0~65535


// ======================================================
// 延时函数
// ======================================================

// ten_us = 1，代表10us
void delay_us(u16 ten_us)
{
    while(ten_us--);
}


// ms = 1，代表1ms
void delay_ms(u16 ms)
{
    u16 i,j;

    for(i=ms;i>0;i--)
        for(j=110;j>0;j--);
}


// ======================================================
// 矩阵按键
// ======================================================

// 封装矩阵按键：线翻转法
u8 key_flix_scan()
{
    u8 keynumber=0;

    // 先设置所有行线为低，列线全部为高
    // 0000 1111
    P1=0X0F;

    if(P1!=0X0F)
    {
        // 消抖
        delay_ms(10);

        // 再次检测
        P1=0X0F;

        // 检测列线
        switch(P1)
        {
            case 0X07:
                keynumber=1;
                break;

            case 0X0B:
                keynumber=2;
                break;

            case 0X0D:
                keynumber=3;
                break;

            case 0X0E:
                keynumber=4;
                break;
        }


        // ==================================================
        // 再翻转
        // 所有列线为低，行线全部为高
        // 1111 0000
        // ==================================================

        P1=0XF0;

        // 检测行线
        switch(P1)
        {
            case 0X70:
                keynumber=keynumber;
                break;

            case 0XB0:
                keynumber=keynumber+4;
                break;

            case 0XD0:
                keynumber=keynumber+8;
                break;

            case 0XE0:
                keynumber=keynumber+12;
                break;
        }


        // =================================================
        //
        // 现在不等待松手，直接返回当前按键。
        // ==================================================
    }

    return keynumber;
}


// ======================================================
// 595芯片
// ======================================================

// 定义595芯片的引脚
sbit SER=P3^4;       // 串行数据输入
sbit rCLK=P3^5;      // 存储寄存器时钟
sbit SRCLK=P3^6;     // 移位寄存器时钟


// ======================================================
// 595：串入并出
// ======================================================

void hc595_Write_data(u8 byte)
{
    u8 i;

    for(i=0;i<8;i++)
    {
        // 准备好高位数据
        SER=byte>>7;

        // 左移一位
        byte<<=1;

        // 移位寄存器时钟
        SRCLK=0;
        SRCLK=1;
    }

    // 存储寄存器时钟
    rCLK=0;
    rCLK=1;
}


// ======================================================
