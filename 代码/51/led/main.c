u8 gled_dz_rows[8]=
{
    0x00,
    0x10,
    0x20,
    0x7C,
    0x7C,
    0x20,
    0x10,
    0x00
};


// ======================================================
// LED点阵列线
// ======================================================

u8 gled_dz_cols[8]=
{
    0x7F,
    0xBF,
    0xDF,
    0xEF,
    0xF7,
    0xFB,
    0xFD,
    0xFE
};


// ======================================================
// 向左移动
// ======================================================

void move_left(u8 arr[],int len)
{
    u8 i;
    u8 temp=arr[0];

    for(i=0;i<len-1;i++)
    {
        arr[i]=arr[i+1];
    }

    arr[len-1]=temp;
}


// ======================================================
// 向右移动
// ======================================================

void move_right(u8 arr[],int len)
{
    u8 i;
    u8 temp=arr[len-1];

    for(i=len-1;i>0;i--)
    {
        arr[i]=arr[i-1];
    }

    arr[0]=temp;
}


// ======================================================
// 向上移动
// ======================================================

void move_up(u8 arr[],int len)
{
    u8 i;

    for(i=0;i<len;i++)
    {
        arr[i]=_crol_(arr[i],1);
    }
}


// ======================================================
// 向下移动
// ======================================================

void move_down(u8 arr[],int len)
{
    u8 i;

    for(i=0;i<len;i++)
    {
        arr[i]=_cror_(arr[i],1);
    }
}


// ======================================================
// LED点阵刷新
// ======================================================

void refresh_led()
{
    u8 i;

    for(i=0;i<8;i++)
    {
        // 先关闭上一列
        hc595_Write_data(0x00);

        // 发送当前列的数据
        hc595_Write_data(gled_dz_rows[i]);

        // 选择当前列
        P0=gled_dz_cols[i];

        // 延时
        delay_ms(2);
    }

    // 关闭点阵
    P0=0xFF;
}


