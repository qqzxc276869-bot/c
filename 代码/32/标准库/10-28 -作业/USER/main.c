/*
 * 功能：通过串口接收一条完整指令，控制两个 LED 和一个有源蜂鸣器。
 *
 * 程序执行顺序：
 * 1. 启动文件调用 SystemInit()，按照 system_stm32f10x.c 配置系统时钟。
 * 2. 进入 main()，配置中断分组、输出引脚和 USART1。
 * 3. main() 留在 while 循环中；串口收到数据时，CPU 转去执行接收中断。
 * 4. 中断每次取出一个字节，收齐并验证 8 个字节后，才操作 LED 或蜂鸣器。
 *
 * 上位机需要用 HEX 模式发送，例如打开 LED1：
 * 18 AA BB 01 CC DD 0D 0A
 * 这里是 8 个二进制字节，不能把这串内容当作普通文本发送。
 */
#include "main.h"

int main(void)
{
    /*
     * 读取当前的时钟配置，重新计算并更新 SystemCoreClock 变量。
     * SystemCoreClock 表示内核使用的 HCLK 频率，单位为 Hz。
     *
     * 此函数只更新变量，不负责打开晶振、配置 PLL 或切换时钟。
     * 真正的时钟初始化已经由启动文件调用的 SystemInit() 完成。
     */
    SystemCoreClockUpdate();

    /*
     * 将 NVIC 的优先级分成：2 位抢占优先级 + 2 位子优先级。
     * 两种优先级的取值范围都是 0～3，数值越小，优先级越高。
     *
     * 抢占优先级决定一个中断能否打断另一个正在执行的中断。
     * 抢占等级相同时，子优先级决定多个挂起中断的处理顺序，
     * 但不会让同一抢占等级的中断互相打断。
     *
     * 分组应先配置好，后面的 uart_init() 再设置串口的具体优先级。
     */
    NVIC_PriorityGroupConfig(NVIC_PriorityGroup_2);

    /*
     * 调用 BSP/GPIO.c 中已有的输出初始化函数：
     * PB5、PE5 配置为推挽输出，并先输出高电平，使两个 LED 熄灭；
     * PB8 配置为推挽输出，并先输出低电平，使有源蜂鸣器关闭。
     *
     * 先初始化输出，再开启串口中断，保证第一条指令到达时，
     * 对应的 GPIO 已经可以正常使用。
     */
    Gpio_Init();

    /*
     * 9600 是串口波特率，单位为 bit/s，不是每秒接收 9600 个字节。
     * uart_init() 内部还会配置：8 位数据、1 位停止位、无校验、无流控。
     * 电脑串口助手也要采用相同设置，并选择 HEX 发送。
     */
    uart_init(9600);

    while (1)
    {
        /*
         * 本例的接收、协议解析和 GPIO 控制都在 USART1_IRQHandler() 中完成，
         * 因此主循环不需要再轮询接收标志，也不需要反复调用 uart_init()。
         *
         * 串口中断到来时，CPU 暂停主循环，执行中断函数；
         * 中断处理完后，再返回主循环继续运行。
         * 以后可以在这里加入其他任务；避免在其他地方长时间关闭中断。
         */
    }
}
